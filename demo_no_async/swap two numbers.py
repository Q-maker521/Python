#使用元组特性实现交换两个变量值
#b,a    ，是元组的标志
a = 12
b = 10
a,b = b,a
print(a,b)

#元组：有序、不可变、可重复
#1.逗号创建元组
t1 = 1,2,3#(元组，等价于(1,2,3))
#常用写法 t1=(1,2,3)
#2.tuple()构造器，把可迭代对象转化为元组
t2 = tuple([1,2,3])#列表转元组(1,2,3)
t3 = tuple("abc")#字符串转元组('a','b','c')

#访问元组
#1.下标索引，从0开始，支持负数索引
print(t1[0],t1[-1])#t1[0]为1，t1[-1]为3
#2.切片
print(t1[1:3])#结果为（2,3）[1:3]相当于左闭右开[1:3)
#3.获取长度
print('t1的结果是',len(t1))#结果为3

#元组本身不可变，，元组存放列表的地址，列表内容可变
#元组常用运算符
#1.+拼接两个元组，返回新元组
t4=t1+t2
print(t4)#(1,2,3,1,2,3)顺序拼接
#2.*重复
t5=(1,)*3
print(t5)#(1,1,1)
#3.in/not in判断成员
print(2 in t1)#true
#4.判断运算符<,>,=
print((1,3)<(1,4))#true,按顺序逐个比较

#内置方法
#1.  .count(元素)，统计元素出现次数
print(t1.count(3))#1
#2.  .index(元素)，查找元素第一次出现的下标，找不到报错
print(t1.index(3))

#序列解包（拆包）左边变量数量和元组元素数量要匹配
#不定长解包用*
t=(1,2,3,4)
a,*rest=t
print(a)#1
print(rest)#[2,3,4]

